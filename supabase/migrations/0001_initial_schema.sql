begin;

create or replace function public.set_updated_at() returns trigger
language plpgsql set search_path = public as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  public_id char(6) not null unique,
  username varchar(32) not null unique,
  display_name varchar(32) not null,
  role text not null default 'user' check (role in ('admin', 'moderator', 'user')),
  email varchar(256) unique,
  email_verified boolean not null default false,
  email_code char(6), email_verification_token char(32),
  description varchar(512), avatar varchar(128),
  settings jsonb not null default '{}'::jsonb,
  is_private boolean not null default false,
  password varchar(256), password_reset char(32), password_reset_expiration timestamptz,
  tokens jsonb not null default '[]'::jsonb,
  two_factor_enabled boolean not null default false,
  two_factor_secret varchar(128), two_factor_temp varchar(128), two_factor_recovery jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  is_deleted boolean not null default false
);

create table if not exists public.groups (
  id bigint generated by default as identity primary key,
  public_id char(6) not null unique,
  name varchar(128) not null, description varchar(512), icon varchar(128),
  is_public boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  created_by bigint not null references public.users(id) on delete restrict,
  is_deleted boolean not null default false
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id bigint not null references public.users(id) on delete cascade,
  sender_id bigint references public.users(id) on delete set null,
  group_id bigint references public.groups(id) on delete cascade,
  type text check (type in ('invite', 'request', 'message', 'alert')),
  subject varchar(100), message varchar(1024),
  action text check (action in ('Accept', 'Decline', 'Request', 'Join', 'Invite', 'Ignore', 'Send Message', 'Reply', 'Delete')),
  is_read boolean not null default false
);

create table if not exists public.associates (
  a bigint not null references public.users(id) on delete cascade,
  b bigint not null references public.users(id) on delete cascade,
  constraint associates_ab_unique unique (a, b),
  constraint associates_ba_unique unique (b, a),
  constraint associates_distinct check (a <> b)
);

create table if not exists public.blocked (
  blocker bigint not null references public.users(id) on delete cascade,
  blocked bigint not null references public.users(id) on delete cascade,
  constraint blocked_pair_unique unique (blocker, blocked),
  constraint blocked_reverse_unique unique (blocked, blocker),
  constraint blocked_distinct check (blocker <> blocked)
);

create table if not exists public.members (
  group_id bigint not null references public.groups(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  role text check (role in ('owner', 'admin', 'student', 'user')),
  primary key (group_id, user_id)
);
create index if not exists members_user_id_idx on public.members(user_id);

create table if not exists public.sources (
  id bigint generated by default as identity primary key,
  public_id char(6) not null unique,
  title varchar(128) not null,
  medium text check (medium in ('book', 'article', 'video', 'podcast', 'website', 'audio')),
  url varchar(512), tags jsonb not null default '[]'::jsonb, credits jsonb not null default '[]'::jsonb,
  created_by bigint not null references public.users(id) on delete restrict,
  published_at timestamptz, last_accessed timestamptz,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  is_deleted boolean not null default false
);

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  public_id char(6) not null unique,
  title varchar(128) not null, text varchar(8192) not null,
  tags jsonb not null default '[]'::jsonb,
  created_by bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  is_deleted boolean not null default false
);

create table if not exists public.quizzes (
  id bigint generated by default as identity primary key,
  public_id char(6) not null unique,
  type text check (type in ('prompt-response', 'multiple-choice', 'fill-in-the-blank', 'ordered-list-answer', 'unordered-list-answer', 'verbatim')),
  prompt varchar(256), choices jsonb not null default '[]'::jsonb,
  answers jsonb not null default '[]'::jsonb, hints jsonb not null default '[]'::jsonb,
  tags jsonb not null default '[]'::jsonb,
  created_by bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  is_deleted boolean not null default false
);

create table if not exists public.user_quizzes (
  user_id bigint not null references public.users(id) on delete cascade,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  level integer not null default 0, tries_at_level integer not null default 0,
  last_correct timestamptz default now(), hidden_until timestamptz default now(),
  primary key (user_id, quiz_id)
);
create index if not exists user_quizzes_quiz_id_idx on public.user_quizzes(quiz_id);

create table if not exists public.resource_contributors (
  resource_id bigint not null,
  user_id bigint not null references public.users(id) on delete cascade,
  type text not null check (type in ('source', 'note', 'quiz')),
  primary key (resource_id, user_id, type)
);
create index if not exists resource_contributors_user_id_idx on public.resource_contributors(user_id);

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  public_id char(6) not null unique,
  name varchar(128), description varchar(512),
  enrollment text check (enrollment in ('open', 'paid', 'private')),
  created_by bigint not null references public.users(id) on delete restrict,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  is_deleted boolean not null default false
);

create table if not exists public.course_users (
  course_id bigint not null references public.courses(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  role text not null default 'student' check (role in ('owner', 'tutor', 'student')),
  expiration timestamptz,
  primary key (course_id, user_id)
);
create index if not exists course_users_user_id_idx on public.course_users(user_id);

create table if not exists public.courses_hierarchy (
  inferior bigint not null references public.courses(id) on delete cascade,
  superior bigint not null references public.courses(id) on delete cascade,
  relationship text not null check (relationship in ('prerequisite', 'encompasses')),
  average_level_required integer not null default 0,
  minimum_level_required integer not null default 0,
  primary key (inferior, superior, relationship),
  constraint courses_hierarchy_distinct check (inferior <> superior)
);
create index if not exists courses_hierarchy_superior_idx on public.courses_hierarchy(superior);

create table if not exists public.resource_relations (
  a bigint not null, b bigint not null,
  a_type text not null check (a_type in ('source', 'note', 'quiz', 'course', 'group')),
  b_type text not null check (b_type in ('source', 'note', 'quiz', 'course', 'group')),
  include_reference boolean not null default false,
  reference varchar(128),
  reference_type text check (reference_type in ('page', 'id', 'section', 'timestamp', 'url')),
  constraint resource_relations_ab_unique unique (a, b, a_type, b_type),
  constraint resource_relations_ba_unique unique (b, a, b_type, a_type)
);

create table if not exists public.resource_permissions (
  resource_id bigint not null,
  resource_type text not null check (resource_type in ('source', 'note', 'quiz', 'course', 'group')),
  group_id bigint references public.groups(id) on delete set null,
  group_locked boolean not null default false,
  all_read boolean not null default false,
  all_write boolean not null default false,
  read jsonb not null default '[]'::jsonb,
  write jsonb not null default '[]'::jsonb,
  primary key (resource_id, resource_type),
  constraint all_write_requires_read check (not all_write or all_read)
);
create index if not exists resource_permissions_group_id_idx on public.resource_permissions(group_id);

create table if not exists public.user_reports (
  id bigint generated by default as identity primary key,
  reporter bigint not null references public.users(id) on delete cascade,
  reported bigint not null references public.users(id) on delete cascade,
  type text check (type in ('spam', 'harassment', 'hate-speech', 'violence', 'nudity', 'other')),
  reason varchar(256), link varchar(256), created_at timestamptz not null default now()
);

create table if not exists public.error_logs (
  id bigint generated by default as identity primary key,
  route varchar(256), name varchar(256), message varchar(1024), code varchar(256),
  stack text, note varchar(1024), triggered_at timestamptz not null default now()
);

do $$
declare table_name text;
begin
  foreach table_name in array array['users','groups','sources','notes','quizzes','courses'] loop
    execute format('drop trigger if exists set_%I_updated_at on public.%I', table_name, table_name);
    execute format('create trigger set_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()', table_name, table_name);
  end loop;
end $$;

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'users','notifications','associates','blocked','groups','members','sources','notes','quizzes',
    'user_quizzes','resource_contributors','courses','course_users','courses_hierarchy',
    'resource_relations','resource_permissions','user_reports','error_logs'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon, authenticated', table_name);
  end loop;
end $$;

revoke all on all sequences in schema public from anon, authenticated;
alter default privileges in schema public revoke all on tables from anon, authenticated;
alter default privileges in schema public revoke all on sequences from anon, authenticated;

commit;
