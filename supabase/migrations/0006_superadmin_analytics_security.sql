begin;

alter table public.users drop constraint if exists users_role_check;
alter table public.users add constraint users_role_check
  check (role in ('superadmin', 'admin', 'moderator', 'user'));
alter table public.users add column if not exists two_factor_temp_expires timestamptz;

alter table public.course_users drop constraint if exists course_users_role_check;
alter table public.course_users add constraint course_users_role_check
  check (role in ('owner', 'admin', 'tutor', 'student'));

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('page_view', 'login', 'registration')),
  path varchar(512),
  user_id bigint references public.users(id) on delete set null,
  visitor_hash char(64),
  user_agent varchar(512),
  created_at timestamptz not null default now()
);
create index if not exists analytics_events_created_at_idx on public.analytics_events(created_at desc);
create index if not exists analytics_events_type_created_at_idx on public.analytics_events(event_type, created_at desc);

create table if not exists public.auth_attempts (
  id bigint generated by default as identity primary key,
  action text not null check (action in ('login', 'register', 'two_factor')),
  identifier_hash char(64) not null,
  ip_hash char(64) not null,
  succeeded boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists auth_attempts_lookup_idx
  on public.auth_attempts(action, identifier_hash, ip_hash, created_at desc);

alter table public.analytics_events enable row level security;
alter table public.auth_attempts enable row level security;
revoke all on table public.analytics_events, public.auth_attempts from anon, authenticated;
revoke all on sequence public.analytics_events_id_seq, public.auth_attempts_id_seq from anon, authenticated;

commit;
