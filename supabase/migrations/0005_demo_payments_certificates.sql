begin;

create table if not exists public.course_payments (
  id bigint generated by default as identity primary key,
  receipt_id char(12) not null unique,
  course_id bigint not null references public.courses(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  amount_cents integer not null check (amount_cents >= 0),
  currency char(3) not null default 'USD',
  status text not null default 'paid' check (status in ('paid', 'refunded')),
  is_demo boolean not null default true,
  created_at timestamptz not null default now(),
  unique (course_id, user_id)
);

create table if not exists public.course_note_progress (
  course_id bigint not null references public.courses(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  note_id bigint not null references public.notes(id) on delete cascade,
  completed_at timestamptz not null default now(),
  primary key (course_id, user_id, note_id)
);

create table if not exists public.course_certificates (
  id bigint generated by default as identity primary key,
  public_id char(12) not null unique,
  course_id bigint not null references public.courses(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  issued_at timestamptz not null default now(),
  unique (course_id, user_id)
);

create index if not exists course_payments_user_id_idx on public.course_payments(user_id);
create index if not exists course_note_progress_user_id_idx on public.course_note_progress(user_id);
create index if not exists course_certificates_user_id_idx on public.course_certificates(user_id);

alter table public.course_payments enable row level security;
alter table public.course_note_progress enable row level security;
alter table public.course_certificates enable row level security;

revoke all on table public.course_payments, public.course_note_progress, public.course_certificates from anon, authenticated;
revoke all on sequence public.course_payments_id_seq, public.course_certificates_id_seq from anon, authenticated;

commit;
